public class OperasiMatematika {
    static void main() {
        int a = 100;
        int b = 10;

        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);

        int c = 100;
        c += 10;
        System.out.println(c);

        c -= 10;
        System.out.println(c);

        c *= 10;
        System.out.println(c);

        c++;
        System.out.println(c);

        c--;
        System.out.println(c);

        Boolean d = true;

        System.out.println(!d);
    }
}
